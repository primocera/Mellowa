/**
 * Lifecycle email templates (Content Elevation v6, Prompt 17).
 *
 * Precise, premium and non-sensitive. Transactional subjects carry no emoji;
 * no email includes mood, stress, meals, allergies, journal or plan content.
 * Billing emails render server-derived plan, exact price and dates when the
 * caller provides them, and fall back to a truthful sentence (pointing to
 * Billing) rather than inventing a number. Plain-text alternatives are
 * generated by the delivery layer (htmlToText).
 */

const BRAND = "#6D8C7D";
const TEXT = "#1F2937";
const MUTED = "#6B7280";

export interface Email {
  subject: string;
  html: string;
}

/** Server-derived billing facts. All three are needed to state an exact charge. */
export interface BillingFacts {
  /** Human plan label, e.g. "Monthly plan". */
  plan?: string;
  /** Already-formatted price with currency, e.g. "€6.99". */
  price?: string;
  /** Already-formatted date, e.g. "17 August 2026". */
  date?: string;
}

function hasExact(f: BillingFacts): f is Required<BillingFacts> {
  return Boolean(f.plan && f.price && f.date);
}

/** Preheader = the preview line most inboxes show next to the subject. */
function shell(bodyHtml: string, preheader: string): string {
  return `<!doctype html><html lang="en"><body style="margin:0;background:#FAF7F2;padding:24px;font-family:-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;color:${TEXT};">
  <span style="display:none!important;visibility:hidden;opacity:0;height:0;width:0;overflow:hidden;">${preheader}</span>
  <div style="max-width:520px;margin:0 auto;background:#ffffff;border-radius:16px;padding:32px;">
    <div style="font-size:20px;font-weight:600;letter-spacing:-0.02em;margin-bottom:20px;">Mellowa</div>
    ${bodyHtml}
    <hr style="border:none;border-top:1px solid #EDE9E2;margin:28px 0 16px;" />
    <p style="font-size:12px;color:${MUTED};line-height:1.6;margin:0;">
      Mellowa is a wellbeing app — not medical care, therapy or emergency support.
      If you're in crisis, please contact your local emergency services.
    </p>
    <p style="font-size:12px;color:${MUTED};line-height:1.6;margin:8px 0 0;">
      Questions? Contact <a href="mailto:${readLegalConfig().supportEmail}" style="color:${BRAND};">${readLegalConfig().supportEmail}</a>.
      This inbox is not monitored for emergencies.
    </p>
  </div>
</body></html>`;
}

function button(label: string, href: string): string {
  // role/aria make the link read as a button to assistive tech.
  return `<a href="${href}" role="button" style="display:inline-block;background:${BRAND};color:#ffffff;text-decoration:none;padding:12px 20px;border-radius:12px;font-weight:600;font-size:15px;">${label}</a>`;
}

function secondaryLink(label: string, href: string): string {
  return `<a href="${href}" style="color:${BRAND};font-size:14px;">${label}</a>`;
}

function p(text: string): string {
  return `<p style="font-size:16px;line-height:1.6;">${text}</p>`;
}


/**
 * MW-V10-02: `trialDays` is the length Stripe actually granted, so a cohort on
 * a different trial length never receives the other arm's number. When it is
 * unknown the copy stays length-neutral instead of guessing.
 */
export function trialStartedEmail(
  facts: BillingFacts = {},
  trialDays: number | null = null
): Email {
  const length = trialDays === null ? null : trialLengthLabel(trialDays);
  const adjective = trialLengthAdjective(trialDays);
  const body = hasExact(facts)
    ? p(
        `Your ${facts.plan} trial is active. You'll be charged ${facts.price} on ${facts.date} unless you cancel before then.`
      )
    : p(
        "Your Mellowa trial is active. You'll be charged when the trial ends unless you cancel before then. Your exact price and date are on the billing page."
      );
  return {
    subject: adjective
      ? `Your ${adjective} Mellowa trial has started.`
      : "Your Mellowa trial has started.",
    html: shell(
      `${body}
       <p style="margin:24px 0;">${button("Open Mellowa", `${appUrl()}/today`)}</p>
       <p style="margin:0;">${secondaryLink("Manage billing", `${appUrl()}/billing`)}</p>`,
      length
        ? `Full access for ${length}. Cancel anytime before it renews.`
        : "Full access for the whole trial. Cancel anytime before it renews."
    ),
  };
}

/**
 * MW-V11: the subject states WHEN the trial ends, computed from the real
 * trial_end in the user's own timezone by the caller. The old copy hard-coded
 * "ends tomorrow" for everyone the daily cron caught within 24h — so a trial
 * ending later today, or one whose mail landed after a delivery lag, arrived
 * announcing a day that had already passed. `daysUntilEnd` is 0 for today,
 * 1 for tomorrow, N for further out; null keeps the length-neutral wording.
 */
function trialEndingSubject(daysUntilEnd: number | null): string {
  if (daysUntilEnd === null) return "Your Mellowa trial ends soon";
  if (daysUntilEnd <= 0) return "Your Mellowa trial ends today";
  if (daysUntilEnd === 1) return "Your Mellowa trial ends tomorrow";
  return `Your Mellowa trial ends in ${daysUntilEnd} days`;
}

export function trialEndingEmail(
  facts: BillingFacts = {},
  daysUntilEnd: number | null = null
): Email {
  const body = hasExact(facts)
    ? p(
        `Your ${facts.plan} trial ends on ${facts.date}. You'll be charged ${facts.price} on that date unless you cancel first.`
      )
    : p(
        "Your Mellowa trial ends soon. You'll be charged on that date unless you cancel first — see billing for the exact price and date."
      );
  return {
    subject: trialEndingSubject(daysUntilEnd),
    html: shell(
      `${body}
       <p style="margin:24px 0;">${button("Manage membership", `${appUrl()}/billing`)}</p>`,
      "Continue automatically, or cancel before you're charged."
    ),
  };
}


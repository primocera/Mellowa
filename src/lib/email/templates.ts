export function canceledEmail(facts: BillingFacts = {}): Email {
  const until = facts.date
    ? `Premium remains available until ${facts.date}. You won't be charged again.`
    : "Premium remains available until the end of your current period. You won't be charged again.";
  return {
    subject: "Your Mellowa plan is canceled",
    html: shell(
      `${p(until)}
       <p style="margin:24px 0;">${button("View membership", `${appUrl()}/billing`)}</p>`,
      "You won't be charged again."
    ),
  };
}

export function paymentFailedEmail(facts: BillingFacts = {}): Email {
  const amount = facts.price
    ? `${facts.price}${facts.plan ? ` for ${facts.plan}` : ""}`
    : null;
  const body = amount
    ? p(
        `We couldn't process ${amount}. Saved plans remain available. Update your payment method to keep creating new Premium plans.`
      )
    : p(
        "We couldn't process your latest payment. Saved plans remain available. Update your payment method to keep creating new Premium plans."
      );
  return {
    subject: "Your Mellowa payment needs attention",
    html: shell(
      `${body}
       <p style="margin:24px 0;">${button("Update payment method", `${appUrl()}/billing`)}</p>`,
      "Update your payment method to keep creating new plans."
    ),
  };
}

